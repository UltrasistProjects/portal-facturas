import sqlite3
from pathlib import Path

import pytest
from alembic import command

from tests.conftest import ROOT, alembic_config

VERSIONS = ROOT / "alembic" / "versions"


@pytest.fixture()
def empty_db(tmp_path) -> tuple[str, Path]:
    path = tmp_path / "migraciones.db"
    return f"sqlite:///{path.as_posix()}", path


def tables(path: Path) -> set[str]:
    with sqlite3.connect(path) as connection:
        rows = connection.execute("SELECT name FROM sqlite_master WHERE type = 'table'").fetchall()
    return {name for (name,) in rows} - {"alembic_version"}


def test_upgrade_head_coincide_con_los_modelos(empty_db):
    url, path = empty_db
    config = alembic_config(url)
    command.upgrade(config, "head")
    command.check(config)  # lanza AutogenerateDiffsDetected si modelos y migraciones difieren
    assert {
        "users",
        "suppliers",
        "contracts",
        "invoices",
        "documents",
        "validation_results",
        "audit_logs",
        "reviews",
    } <= tables(path)


def test_downgrade_de_la_revision_inicial_no_destruye_datos(empty_db):
    url, path = empty_db
    config = alembic_config(url)
    command.upgrade(config, "0001_initial")
    before = tables(path)
    with pytest.raises(NotImplementedError, match="Restaure un respaldo"):
        command.downgrade(config, "base")
    assert tables(path) == before


def test_revisiones_explicitas_sin_create_all_ni_modelos():
    revisions = list(VERSIONS.glob("*.py"))
    assert revisions
    for revision in revisions:
        source = revision.read_text(encoding="utf-8")
        for forbidden in ("create_all", "drop_all", "app.models"):
            assert forbidden not in source, f"{revision.name} contiene {forbidden}"
    assert "op.create_table" in (VERSIONS / "0001_initial.py").read_text(encoding="utf-8")
